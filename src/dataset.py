def hard_turns():
    out = []
    for i, s in enumerate(HARD, 1):
        for v in ("en", "hi", "hx"):
            out.append(dict(id=f"h{i:02d}-{v}", scenario=100 + i, lang=v, agent=s["agent"][v], caller=s["caller"][v],
                            intent=s["intent"], intent_ok=[s["intent"], *s["ok"]], esc=s["esc"], done=s["done"],
                            reply=(s["reply"] or DEFAULT_REPLY)[v], tags=s["tags"], hard=True))
    return out


