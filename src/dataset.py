DEFAULT_REPLY = {"en": "english", "hi": "hindi", "hx": "hindi"}


def turns():
    out = []
    for i, s in enumerate(SCENARIOS, 1):
        for v in ("en", "hi", "hx"):
            out.append(dict(
                id=f"s{i:02d}-{v}", scenario=i, lang=v,
                agent=s["agent"][v], caller=s["caller"][v],
                intent=s["intent"], intent_ok=[s["intent"], *s["ok"]],
                esc=s["esc"], done=s["done"],
                reply=(s["reply"] or DEFAULT_REPLY)[v],
                tags=s["tags"],
            ))
    return out


